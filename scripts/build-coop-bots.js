'use strict';
/* node scripts/build-coop-bots.js  ->  js/coop-bots.js
   Bundles the headless test bots (test/duo-bots/*.js, test/squad-bots/*.js) so the CO-OP TEST mode can use them as the computer
   partner in the browser. Re-run after adding or changing a bot; test/coop-bots.test.js fails when the bundle is stale. */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const part = (dir, key) => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith('.js')).sort()
  .map(f => `  /* ${dir}/${f} */\n  ${key}((() => { const module = { exports: {} }; (function (module, process) {\n${fs.readFileSync(path.join(root, dir, f), 'utf8')}\n  })(module, { env: {} }); return module.exports; })());`).join('\n');
const out = `'use strict';
/* GENERATED by scripts/build-coop-bots.js from test/duo-bots and test/squad-bots. Do not edit. */
window.COOP_BOTS = (() => {
  const all = {};
  const add = o => Object.assign(all, o);
${part('test/duo-bots', 'add')}
${part('test/squad-bots', 'add')}
  return all;
})();
`;
if (process.argv[2] === '--check') { const cur = fs.existsSync(path.join(root, 'js/coop-bots.js')) ? fs.readFileSync(path.join(root, 'js/coop-bots.js'), 'utf8') : ''; if (cur !== out) { console.error('js/coop-bots.js is stale: run node scripts/build-coop-bots.js'); process.exit(1); } console.log('coop-bots.js up to date'); }
else { fs.writeFileSync(path.join(root, 'js/coop-bots.js'), out); console.log('wrote js/coop-bots.js', out.length, 'bytes'); }
